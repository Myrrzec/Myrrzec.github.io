const TITLES = {
  en: "Make — Web Developer",
  ru: "Make — Веб-разработчик",
};

const DESCS = {
  en: "Make is a web developer: full-stack apps and websites, from idea to a live URL. Two live projects with source code.",
  ru: "Make, веб-разработчик: full-stack приложения и сайты от идеи до рабочей ссылки. Два живых проекта с исходным кодом.",
};

const nodes = [...document.querySelectorAll("[data-i18n]")];
nodes.forEach((el) => (el.dataset.en = el.innerHTML));
const metaDesc = document.querySelector('meta[name="description"]');

function setLang(lang) {
  nodes.forEach((el) => {
    const key = el.dataset.i18n;
    el.innerHTML = lang === "ru" && RU[key] ? RU[key] : el.dataset.en;
  });
  document.documentElement.lang = lang;
  document.title = TITLES[lang];
  metaDesc.setAttribute("content", DESCS[lang]);
  document.querySelectorAll(".lang button").forEach((b) => {
    b.setAttribute("aria-pressed", String(b.dataset.lang === lang));
  });
  try {
    localStorage.setItem("lang", lang);
  } catch {}
}

document.querySelectorAll(".lang button").forEach((b) => {
  b.addEventListener("click", () => setLang(b.dataset.lang));
});

let saved = "en";
try {
  saved = localStorage.getItem("lang") || "en";
} catch {}
if (saved === "ru") setLang("ru");
